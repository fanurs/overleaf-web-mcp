import { readFileSync, writeFileSync } from 'node:fs'
import { Buffer } from 'node:buffer'
import process from 'node:process'

// Deterministic, uncompressed ZIP. Package only these reviewed sources, never a browser profile.
const files = ['manifest.json', 'popup.html', 'popup.css', 'popup.js', 'session.js', 'README.md']
const parts = [],
  directory = []
let offset = 0
function crc32(bytes) {
  let crc = 0xffffffff
  for (const byte of bytes) {
    crc ^= byte
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0)
  }
  return (crc ^ 0xffffffff) >>> 0
}
for (const file of files) {
  const name = Buffer.from(file)
  const data = readFileSync(new URL('../extension/' + file, import.meta.url))
  const crc = crc32(data)
  const header = Buffer.alloc(30)
  header.writeUInt32LE(0x04034b50, 0)
  header.writeUInt16LE(20, 4)
  header.writeUInt16LE(0x21, 12) // 1980-01-01, reproducible timestamp.
  header.writeUInt32LE(crc, 14)
  header.writeUInt32LE(data.length, 18)
  header.writeUInt32LE(data.length, 22)
  header.writeUInt16LE(name.length, 26)
  parts.push(header, name, data)
  const central = Buffer.alloc(46)
  central.writeUInt32LE(0x02014b50, 0)
  central.writeUInt16LE(20, 4)
  central.writeUInt16LE(20, 6)
  central.writeUInt16LE(0x21, 14)
  central.writeUInt32LE(crc, 16)
  central.writeUInt32LE(data.length, 20)
  central.writeUInt32LE(data.length, 24)
  central.writeUInt16LE(name.length, 28)
  central.writeUInt32LE(offset, 42)
  directory.push(central, name)
  offset += header.length + name.length + data.length
}
const central = Buffer.concat(directory)
const end = Buffer.alloc(22)
end.writeUInt32LE(0x06054b50, 0)
end.writeUInt16LE(files.length, 8)
end.writeUInt16LE(files.length, 10)
end.writeUInt32LE(central.length, 12)
end.writeUInt32LE(offset, 16)
const zip = Buffer.concat([...parts, central, end])
const target = new URL('../src/extension-package.ts', import.meta.url)
const source =
  '// Generated by cloudflare/scripts/package-extension.mjs. No credentials.\nexport const EXTENSION_ZIP =\n  ' +
  JSON.stringify(zip.toString('base64')).replaceAll('"', "'") +
  '\n'
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== source)
    throw new Error('Extension package is stale. Run npm run build:extension.')
} else {
  writeFileSync(target, source)
  if (process.argv[2]) writeFileSync(process.argv[2], zip)
}
console.log('Extension package verified (' + zip.length + ' bytes, ' + files.length + ' source files).')
